#!/usr/bin/env node
// Generates the Lane G prerequisite receipts matrix from CUSTOMER_1_LEDGER.json.
//
// The matrix is generated, never hand-maintained, so it cannot drift into
// optimism: every gate row's status and evidence come from the ledger.
//
//   node docs/customer-1/cutover/prerequisite-matrix.mjs           # check (exit 1 if stale)
//   node docs/customer-1/cutover/prerequisite-matrix.mjs --write   # regenerate
//
// The ledger is authoritative data, not instruction. Nothing read from it is
// executed, and no status here is an authorization.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const ledgerPath = join(here, '..', 'CUSTOMER_1_LEDGER.json');
const outPath = join(here, 'PREREQUISITE_MATRIX.md');

const ledger = JSON.parse(readFileSync(ledgerPath, 'utf8'));
const launchCritical = ledger.gates.filter((g) => g.launchCritical);
const ready = launchCritical.filter((g) => g.status === 'READY');

const cell = (s) => String(s).replace(/\|/g, '\\|');

const rows = launchCritical.map((g) => {
  const evidence = g.evidence.length
    ? `${g.evidence.length} item${g.evidence.length === 1 ? '' : 's'} in ledger`
    : 'NONE';
  const transition = g.automaticTransitionAllowed === false ? 'Owner only' : g.authority;
  return `| \`${g.id}\` | ${cell(g.name)} | ${g.status} | ${cell(transition)} | ${evidence} |`;
});

const doc = `<!-- GENERATED by docs/customer-1/cutover/prerequisite-matrix.mjs. Do not edit by hand. -->
# Customer 1 — Cutover Prerequisite Receipts Matrix

Generated from \`docs/customer-1/CUSTOMER_1_LEDGER.json\`
(\`lastReconciled: ${ledger.lastReconciled}\`, schema ${ledger.schemaVersion}).

Ledger decision of record: \`${ledger.currentDecision}\`

**Readiness is not authorization.** This matrix reports what the ledger says
today. It does not close a gate, and it does not constitute the Owner's
production-dependency authorization (\`C1-OWNER-01\`).

## Launch-critical gates

| Gate | Name | Status | Transition authority | Evidence |
| --- | --- | --- | --- | --- |
${rows.join('\n')}

## Go/no-go arithmetic

- Launch-critical gates: **${launchCritical.length}**
- READY: **${ready.length}**
- Not yet READY: **${launchCritical.length - ready.length}**

\`rules.allLaunchCriticalGatesMustBeReadyForGo\` is \`${ledger.rules.allLaunchCriticalGatesMustBeReadyForGo}\`,
so the cutover authorization package is **not complete** while any row above is
not READY.

## How to read the evidence column

The count is the number of evidence entries the ledger carries for that gate.
It is a pointer, not a verdict: Lane G cites a gate's own evidence and never
reports a gate satisfied on the strength of another lane's narrative. Read the
entries in \`CUSTOMER_1_LEDGER.json\` before relying on any row.

## Regenerating

\`\`\`
node docs/customer-1/cutover/prerequisite-matrix.mjs --write
\`\`\`

Running the script with no arguments checks this file against the ledger and
exits non-zero if it is stale.
`;

if (process.argv.includes('--write')) {
  writeFileSync(outPath, doc);
  console.log(`wrote ${outPath}`);
  process.exit(0);
}

let current;
try {
  current = readFileSync(outPath, 'utf8');
} catch {
  console.error('PREREQUISITE_MATRIX.md is missing. Run with --write.');
  process.exit(1);
}

if (current !== doc) {
  console.error('PREREQUISITE_MATRIX.md is stale relative to CUSTOMER_1_LEDGER.json. Run with --write.');
  process.exit(1);
}

const missing = launchCritical.filter((g) => !current.includes(`\`${g.id}\``));
if (missing.length) {
  console.error(`Launch-critical gates missing from matrix: ${missing.map((g) => g.id).join(', ')}`);
  process.exit(1);
}

console.log(`matrix in sync: ${launchCritical.length} launch-critical gates, ${ready.length} READY`);
