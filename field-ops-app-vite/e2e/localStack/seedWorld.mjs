#!/usr/bin/env node
// LOCAL GOVERNED STACK -- seed a synthetic world with the four Parts-family personas. TEST INFRASTRUCTURE ONLY.
//
//   node e2e/localStack/seedWorld.mjs            (idempotent; every step checks before it writes)
//
// WHAT IT BUILDS, ALL THROUGH THE REPOSITORY'S OWN GOVERNED PATHS (no hand-inserted capability row, ever):
//   1. a fresh database on the loopback Postgres, migrated by the normal runner;
//   2. a bootstrapped tenant with its seeded Roles, its first administrator and its owner (the same bootstrap the
//      Sample Company Postgres proof uses);
//   3. the Sample Company v2 world (scripts/seedSampleCompany.js --mode apply): the synthetic Employees, their
//      Principals and Security Roles, warehouses SC-WH-*, suppliers, reorder/PO/receiving rows, and the Role ->
//      capability grants reconciled from the governed Role catalog;
//   4. the Roles each persona holds in nonprod that the manifest does not name (docs/uat/data/personas.csv `globalRoles`),
//      assigned with the governed assignRole command, plus their grant reconciliation;
//   5. warehouses taylor-main / taylor-service, the persona Operational Scopes (governed assignEmployeeOperationalScope),
//      a minimal synthetic Parts catalog (PRT-1001 ...), its supplier terms, and a Reorder request with a recorded
//      purchase order so Receiving has an ORDERED candidate;
//   6. one EOS human login per persona (password + TOTP + recovery codes) through scripts/enrollPersonaLogins.js
//      --employees, credentials written to EOS_NET_STATE_DIR (outside the repository, mode 0600, never printed).
//
// It refuses any non-loopback database (stackEnv.mjs). Every secret is a LOCAL TEST VALUE it generates.
import { spawnSync } from "node:child_process";
import { createRequire } from "node:module";
import { existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { randomUUID } from "node:crypto";
import { join } from "node:path";
import { apiEnv, FUNCTIONS_DIR, REPO_ROOT, stackConfig } from "./stackEnv.mjs";
import { PERSONAS } from "../support/personas.mjs";

const require = createRequire(join(FUNCTIONS_DIR, "package.json"));
const pg = require("pg");
const cfg = stackConfig();
const env = apiEnv(cfg);
mkdirSync(cfg.stateDir, { recursive: true });
const log = (m) => process.stdout.write(`[seedWorld] ${m}\n`);
const PERFORMED_BY = "browser-network-harness";

function run(label, script, args, { allowFail = false, extraEnv = {} } = {}) {
  const r = spawnSync(process.execPath, [script, ...args], {
    cwd: FUNCTIONS_DIR, env: { ...env, ...extraEnv }, encoding: "utf8", maxBuffer: 256 * 1024 * 1024,
  });
  if (r.status !== 0 && !allowFail) {
    process.stderr.write(`[seedWorld] ${label} FAILED (exit ${r.status})\n${(r.stderr || "").slice(-4000)}\n${(r.stdout || "").slice(-2000)}\n`);
    process.exit(2);
  }
  return r;
}

// ---- 1. database ------------------------------------------------------------------------------------------------------------
const lib = (p) => require(join(FUNCTIONS_DIR, "lib", p));
const MIGRATE = "node_modules/node-pg-migrate/bin/node-pg-migrate.js";
const migrateUp = (count) => run("migrate", MIGRATE, ["up", "--migrations-dir", "migrations", "--no-check-order", ...(count === undefined ? [] : [String(count)])]);
const dbName = cfg.database.replace(/[^a-z0-9_]/gi, "");
{
  const admin = new pg.Client({ connectionString: cfg.adminDatabaseUrl });
  await admin.connect();
  if (process.argv.includes("--reset")) {
    // Only ever this lane's own database (named by EOS_NET_DB_NAME on a loopback server).
    await admin.query(`DROP DATABASE IF EXISTS ${dbName} WITH (FORCE)`);
    log(`dropped database ${dbName}`);
    // The enrolled logins went with it: their credentials file is this harness's own artifact, regenerated by the next enrolment.
    if (existsSync(cfg.credentialsFile)) unlinkSync(cfg.credentialsFile);
  }
  const exists = (await admin.query("SELECT 1 FROM pg_database WHERE datname = $1", [cfg.database])).rowCount > 0;
  if (!exists) await admin.query(`CREATE DATABASE ${dbName}`);
  await admin.end();
  log(exists ? `database ${cfg.database} exists` : `created database ${cfg.database}`);
}

const pool = new pg.Pool({ connectionString: cfg.databaseUrl, max: 4 });
const { PostgresPolicyRepository } = lib("adminPolicy/postgresPolicyRepository.js");
const { bootstrapAdministrator, ensureTenantPrincipal, bootstrapFirstOwner } = lib("adminPolicy/tenantBootstrap.js");
const repo = new PostgresPolicyRepository(pool);
const ADMIN_SUBJECT = "local-harness-administrator";
const admin = (operation, input) => lib("adminPolicy/adminPolicyApi.js").executeAdminOperation({ repo },
  { caller: { externalSubject: ADMIN_SUBJECT, identityProvider: "firebase" }, operation, input, requestId: `r-${randomUUID()}` });
const mustAdmin = async (operation, input) => {
  const r = await admin(operation, input);
  if (!r.ok) { process.stderr.write(`[seedWorld] ${operation} refused: ${r.code} ${r.message}\n`); process.exit(2); }
  return r;
};

// ---- 2. the governed NONPROD AUTHORITY REPLAY ---------------------------------------------------------------------------------
// Exactly the recipe test/governedNonprodReplayPostgres.test.mjs proves reproduces nonprod's authority from the repository
// alone: migrate to the seed boundary, seed the tenant's Roles, migrate the rest, apply the authority baseline (canonical catalog
// + nonprod activation), bootstrap the administrator, replay decision D-A, then EVERY recorded Administration delta through the
// Administration API. No capability row is hand-inserted outside those repository-owned lists.
const tenantKey = cfg.tenantKey;
const migrationsApplied = await pool.query("SELECT to_regclass('public.pgmigrations') AS t").then(async (r) => (r.rows[0].t ? (await pool.query("SELECT count(*)::int AS n FROM public.pgmigrations")).rows[0].n : 0));
let tenant;
let adminPrincipal;
let ownerPrincipal;
if (migrationsApplied === 0) {
  const baseline = lib("adminPolicy/roleCapabilityAuthorityBaseline.js");
  const files = readdirSync(join(FUNCTIONS_DIR, "migrations")).filter((f) => f.endsWith(".sql")).sort();
  migrateUp(files.filter((f) => f < baseline.SEED_BOUNDARY_MIGRATION).length);
  await pool.query("INSERT INTO eos_policy.tenants (id,key,name) VALUES ($1,$1,$1)", [tenantKey]);
  await lib("adminPolicy/seed/policySeed.js").seedTenantPolicy(repo, tenantKey, PERFORMED_BY);
  migrateUp();
  for (const [pairs, by] of [[baseline.GLOBAL_CATALOG_ACTIVATED_GRANTS, "canonical-catalog:harness"], [baseline.NONPROD_ACTIVATED_CAPABILITY_GRANTS, "nonprod-activation:harness"]]) {
    for (const { roleKey, capabilityKey } of pairs) {
      await pool.query(`INSERT INTO eos_policy.role_capabilities (id,tenant_id,role_id,capability_id,granted_by,created_by,updated_by)
               SELECT 'rc_' || substr(md5($1 || r.id || c.id), 1, 24), $1, r.id, c.id, $4, $4, $4
                 FROM eos_policy.roles r, eos_policy.capabilities c WHERE r.tenant_id = $1 AND r.key = $2 AND c.key = $3
               ON CONFLICT (tenant_id, role_id, capability_id) DO NOTHING`, [tenantKey, roleKey, capabilityKey, by]);
    }
  }
  for (const company of ["taylor", "ventana"]) {
    await pool.query(`INSERT INTO eos_policy.tenant_operating_companies (tenant_id,operating_company_id,status,source,established_by,updated_by)
             VALUES ($1,$2,'ACTIVE','fixture','fixture','fixture')`, [tenantKey, company]);
    await pool.query(`INSERT INTO eos_policy.tenant_operating_company_keys (tenant_id,operating_company_id,operating_company_key,status,provenance,source,established_by,updated_by)
             VALUES ($1,$2,$2,'ACTIVE','NATIVE','fixture','fixture','fixture')`, [tenantKey, company]);
  }
  await bootstrapAdministrator(repo, { tenantId: tenantKey, externalSubject: ADMIN_SUBJECT, performedBy: PERFORMED_BY, reason: "initial administrator" });
  for (const [objectKey, actionKey] of [["opportunity", "edit"], ["opportunity", "createSalesOrder"], ["salesAgreement", "create"],
    ["salesAgreement", "edit"], ["salesAgreement", "accept"], ["salesOrder", "edit"]]) {
    await mustAdmin("revokeObjectActionFromRole", { roleKey: "dispatcher", objectKey, actionKey, reason: "D-A replayed" });
  }
  const roles = lib("adminPolicy/recordedAdministrationRolesDelta.js");
  const stages = [
    lib("adminPolicy/serviceActivationAuthorityDelta.js").serviceActivationOperations(),
  ];
  for (const ch of roles.RECORDED_TENANT_SALES_CHANNELS) {
    await pool.query(`INSERT INTO eos_policy.tenant_sales_channels (tenant_id,sales_channel,status,source,established_by,updated_by) VALUES ($1,$2,'ACTIVE','replay','replay','replay') ON CONFLICT DO NOTHING`, [tenantKey, ch]);
  }
  const d = (m) => lib(`adminPolicy/${m}.js`);
  stages.push(
    roles.commercialSharedContextOperations(),
    d("salesManagerParityDelta").salesManagerActivationOperations(),
    d("serviceActivationAuthorityDelta").serviceExperienceOperations(),
    d("recordedActivationDecisionsDelta").recordedActivationOperations(),
    roles.operationalConfigurationAdministratorOperations(),
    d("partsPurchasingReceivingDelta").partsPurchasingReceivingOperations(),
    d("purchasingFinanceClosureDelta").purchasingFinanceClosureOperations(),
    d("inventoryWarehouseActivationDelta").inventoryWarehouseGrantOperations(),
    d("equipmentActivationDelta").equipmentActivationOperations(),
    d("truckInventoryActivationDelta").truckInventoryActivationOperations(),
  );
  for (const ops of stages) for (const { operation, input } of ops) await mustAdmin(operation, input);
  const n = (await pool.query("SELECT count(*)::int AS n FROM eos_policy.role_capabilities WHERE tenant_id = $1", [tenantKey])).rows[0].n;
  log(`nonprod authority replay applied: ${n} Role->capability grants (the repository's pinned replay count is 797)`);
  tenant = await repo.getTenantByKey(tenantKey);
  adminPrincipal = await repo.getPrincipalBySubject("firebase", ADMIN_SUBJECT);
  ownerPrincipal = await ensureTenantPrincipal(repo, {
    tenantId: tenant.id, externalSubject: "local-harness-owner", identityProvider: "firebase",
    displayName: "Local harness owner", actorUid: PERFORMED_BY, actorRoleKeys: ["admin"],
  });
  await bootstrapFirstOwner(repo, { tenantId: tenant.id, principalId: ownerPrincipal.id, performedBy: PERFORMED_BY,
    reason: "Local browser network harness: the owner Principal the Sample Company seed adopts" });
} else {
  migrateUp();
  tenant = await repo.getTenantByKey(tenantKey);
  adminPrincipal = await repo.getPrincipalBySubject("firebase", ADMIN_SUBJECT);
  ownerPrincipal = await repo.getPrincipalBySubject("firebase", "local-harness-owner");
  log("tenant authority already replayed");
}
const tenantId = tenant.id;
const IDENTITY = ["--tenantKey", cfg.tenantKey, "--existingAdminPrincipalId", adminPrincipal.id, "--existingOwnerPrincipalId", ownerPrincipal.id, "--performedBy", PERFORMED_BY];

// ---- 3. Sample Company v2 ------------------------------------------------------------------------------------------
{
  const r = run("seedSampleCompany", "scripts/seedSampleCompany.js",
    ["--environment", "platform-sandbox", "--databaseUrlEnv", "DATABASE_URL", ...IDENTITY, "--mode", "apply", "--apply"]);
  const out = JSON.parse(r.stdout);
  log(`Sample Company apply: pass=${out.pass} totals=${JSON.stringify(out.totals)}`);
}

// ---- 4. the Roles nonprod grants the personas beyond the manifest (the Administration API's own assignRole) --------------
const roleRows = await repo.listRoles(tenantId);
const roleByKey = new Map(roleRows.map((r) => [r.key, r]));
const roleKeyById = new Map(roleRows.map((r) => [r.id, r.key]));
for (const persona of PERSONAS) {
  const link = await pool.query(
    "SELECT principal_id FROM eos_policy.employee_principal_links WHERE tenant_id = $1 AND employee_id = $2 AND status = 'active'", [tenantId, persona.employeeId]);
  if (link.rowCount !== 1) { process.stderr.write(`[seedWorld] no active Principal link for ${persona.employeeId}\n`); process.exit(2); }
  const principalId = link.rows[0].principal_id;
  persona.principalId = principalId;
  const held = new Set((await repo.listAssignmentsForPrincipal(tenantId, principalId)).filter((a) => a.status === "active").map((a) => roleKeyById.get(a.roleId)));
  for (const key of persona.nonprodRoles) {
    if (held.has(key)) continue;
    const role = roleByKey.get(key);
    if (!role) { process.stderr.write(`[seedWorld] Role ${key} is not defined in this tenant\n`); process.exit(2); }
    await mustAdmin("assignRole", { principalId, roleId: role.id, reason: `Local harness mirror of the nonprod ${persona.label} Role ${key} (docs/uat/data/personas.csv globalRoles)` });
    log(`assigned ${key} -> ${persona.key}`);
  }
}

// ---- 4b. live Role-grant parity -----------------------------------------------------------------------------------------------
// The repository's recorded replay stops short of nonprod's live Role grants in two places for these Roles: nonprod's
// purchasingManager holds the seven SUP-1 supplier-terms / cost grants (Owner-executed after #230), and the live partsAssociate,
// partsManager and purchasingManager no longer hold finance.payment.read (migration 1761609600000 granted it; a later live decision
// removed it). docs/uat/data/role-capability-grants.csv is the measured live Role -> capability table, so the persona Roles' rows
// are brought to it through the Administration API's own grant / revoke operations (never SQL), and every change is reported.
{
  const csv = readFileSync(join(REPO_ROOT, "docs/uat/data/role-capability-grants.csv"), "utf8").trim().split(/\r?\n/).slice(1).map((l) => l.split(","));
  const personaRoles = new Set(PERSONAS.flatMap((p) => p.nonprodRoles));
  const live = new Map(csv.filter((r) => personaRoles.has(r[0])).map((r) => [`${r[0]}|${r[1]}`, { roleKey: r[0], capability: r[1], objectKey: r[2], actionKey: r[3] }]));
  const objectAction = new Map(csv.map((r) => [r[1], { objectKey: r[2], actionKey: r[3] }]));
  const held = (await pool.query(
    "SELECT r.key AS role, c.key AS cap FROM eos_policy.role_capabilities rc JOIN eos_policy.roles r ON r.id=rc.role_id JOIN eos_policy.capabilities c ON c.id=rc.capability_id WHERE rc.tenant_id=$1 AND r.key = ANY($2)",
    [tenantId, [...personaRoles]])).rows.map((r) => `${r.role}|${r.cap}`);
  const heldSet = new Set(held);
  const changes = { granted: [], revoked: [] };
  for (const [k, g] of live) {
    if (heldSet.has(k)) continue;
    await mustAdmin("grantObjectActionToRole", { roleKey: g.roleKey, objectKey: g.objectKey, actionKey: g.actionKey, reason: "Local harness: mirror the live Role grant (docs/uat/data/role-capability-grants.csv)" });
    changes.granted.push(k);
  }
  for (const k of heldSet) {
    if (live.has(k)) continue;
    const [roleKey, capability] = k.split("|");
    const oa = objectAction.get(capability);
    if (!oa) { process.stderr.write(`[seedWorld] cannot revoke ${k}: no object/action in the live table\n`); process.exit(2); }
    await mustAdmin("revokeObjectActionFromRole", { roleKey, objectKey: oa.objectKey, actionKey: oa.actionKey, reason: "Local harness: mirror the live Role grant removal (docs/uat/data/role-capability-grants.csv)" });
    changes.revoked.push(k);
  }
  log(`live Role-grant parity: granted ${changes.granted.length} [${changes.granted.join(", ")}], revoked ${changes.revoked.length} [${changes.revoked.join(", ")}]`);
}

// ---- 5. warehouses, scopes, catalog, supplier terms, reorder ---------------------------------------------------------
const world = { tenantId, adminPrincipalId: adminPrincipal.id, partId: "PRT-1001", personas: {} };
const warehouseBins = lib("eosOps/warehouseBinRepository.js");
const sample = JSON.parse(readFileSync(join(FUNCTIONS_DIR, "scripts/fixtures/sampleCompany.v2.json"), "utf8"));
// The persona world is the real Taylor company (the Employees are in company `taylor`); the Sample Company rows keep their own key.
const companyKey = "taylor";
for (const [warehouseId, name, siteLabel] of [["taylor-main", "Taylor Main Warehouse (local harness)", "Taylor Main"], ["taylor-service", "Taylor Service Warehouse (local harness)", "Taylor Service"]]) {
  if (!(await warehouseBins.readWarehouse(pool, tenantId, warehouseId))) {
    await warehouseBins.createWarehouse(pool, tenantId, PERFORMED_BY, { warehouseId, name, siteLabel, status: "ACTIVE", provenance: "NATIVE", operatingCompanyKey: companyKey });
    log(`created warehouse ${warehouseId}`);
  }
}

// Parts: the governed Part Master writer (the same one the catalog tests use).
const partWriter = lib("catalogMaster/postgresPartMasterWriter.js");
const partActor = Object.freeze({ tenantId, principalId: adminPrincipal.id, capabilities: new Set(["inventory.catalog.manage", "inventory.catalog.activate", "equipment.model.manage"]) });
const PARTS = [
  ["PRT-1001", "Evaporator Fan Motor", "Refrigeration"], ["PRT-1002", "Condenser Fan Blade", "Refrigeration"],
  ["PRT-1003", "Door Gasket 36in", "Seals & Gaskets"], ["PRT-1004", "Thermostat Probe", "Controls"],
  ...sample.parts.records.map((p) => [p.partId, p.name, "Fixture"]),
];
let tick = 0;
const deps = { pool, now: () => new Date(Date.UTC(2026, 9, 1, 12, 0, 0, tick++)) };
for (const [partId, name, category] of PARTS) {
  const found = await pool.query("SELECT 1 FROM eos_ops.parts WHERE tenant_id = $1 AND id = $2", [tenantId, partId]);
  if (found.rowCount > 0) continue;
  await partWriter.createPart(deps, partActor, { part: {
    partId, internalPartNumber: partId, name, status: "ACTIVE", category, stockingUnit: "EACH", controlType: "STANDARD",
    stockingClass: "STOCKED", flags: { expiryTracked: false, consumable: false, returnableCore: false }, wholeUnit: false,
  } });
  log(`created part ${partId}`);
}

// Supplier terms for PRT-1001 (the Sample Company supplier SC-SUP-ACME), preferred.
const supplierCatalog = lib("eosOps/supplierCatalogRepository.js");
if (!(await supplierCatalog.readSupplierCatalogItem(pool, tenantId, "PRT-1001", "SC-SUP-ACME"))) {
  const created = await supplierCatalog.createSupplierCatalogItem(pool, tenantId, PERFORMED_BY, {
    partId: "PRT-1001", supplierId: "SC-SUP-ACME", supplierSku: "ACME-FAN-1001", cost: 18500, currency: "USD", leadTimeDays: 6, minOrderQty: 1,
  });
  await supplierCatalog.setPreferredSupplier(pool, tenantId, PERFORMED_BY, "PRT-1001", "SC-SUP-ACME", created.version);
  log("created supplier terms for PRT-1001");
}

// A Reorder request for PRT-1001 with a recorded purchase order (an ORDERED Receiving candidate).
const purchasing = lib("eosOps/purchasingRepository.js");
const RR_NUMBER = "RR-2026-000950";
let rr = await pool.query("SELECT id FROM eos_ops.reorder_requests WHERE tenant_id = $1 AND reorder_request_number = $2", [tenantId, RR_NUMBER]);
if (rr.rowCount === 0) {
  const request = await purchasing.createReorderRequest(pool, tenantId, adminPrincipal.id, companyKey, {
    partId: "PRT-1001", warehouseId: "taylor-main", status: "PURCHASING_IN_PROGRESS", requestedQuantity: 6, recommendedQuantity: 6, reorderRequestNumber: RR_NUMBER,
  });
  await purchasing.recordPurchaseOrder(pool, tenantId, adminPrincipal.id, request.id, {
    supplierName: "SYNTHETIC Acme Parts Supply (fixture)", externalPoNumber: "LOCAL-PO-000950", orderedQuantity: 6, orderedDate: "2026-10-20",
    expectedArrivalDate: "2026-10-27", unitPriceMinor: 18500, currency: "USD",
  });
  rr = await pool.query("SELECT id FROM eos_ops.reorder_requests WHERE tenant_id = $1 AND reorder_request_number = $2", [tenantId, RR_NUMBER]);
  log("created reorder request + purchase order for PRT-1001");
}
world.requestId = rr.rows[0].id;
world.reorderRequestNumber = RR_NUMBER;

// Operational Scopes: the governed command, as the persona-authority seed calls it.
{
  const { assignEmployeeOperationalScope } = lib("eosWorkforce/commands/employeeOperationalScopeCommands.js");
  const { resolveEmployeeAdministrationActor } = lib("eosWorkforce/commands/employeeAdministrationAuthority.js");
  const actor = await resolveEmployeeAdministrationActor(pool, { tenantId, principalId: adminPrincipal.id });
  for (const persona of PERSONAS) {
    for (const scope of persona.scopes) {
      const [scopeType, scopeId] = scope.split(":");
      try {
        const result = await assignEmployeeOperationalScope({ pool }, actor, { employeeId: persona.employeeId, scopeType, scopeId, reason: `Local harness mirror of the nonprod ${persona.label} scope ${scope}` });
        log(`scope ${scope} -> ${persona.key}: ${result.outcome}`);
      } catch (err) {
        // The governed command now refuses a scope in a warehouse of a company the Employee has no authority in (the SC-WH-*
        // Sample Company warehouses carry their own company key). Nonprod's existing rows for those are INERT for the same
        // reason, so the effective authority is unchanged; the refusal is reported, not hidden.
        log(`scope ${scope} -> ${persona.key}: REFUSED by the governed command (${err.code ?? err.message})`);
        (world.scopesNotAssigned ??= []).push({ persona: persona.key, scope, code: err.code ?? String(err.message) });
      }
    }
  }
}

// ---- 6. EOS human logins -----------------------------------------------------------------------------------------------
if (existsSync(cfg.credentialsFile)) {
  log("credentials file exists: logins already enrolled (never re-enrolled, never overwritten)");
} else {
  const r = run("enrollPersonaLogins", "scripts/enrollPersonaLogins.js", [
    "--environment", "platform-sandbox", "--databaseUrlEnv", "DATABASE_URL", "--tenantKey", cfg.tenantKey,
    "--employees", PERSONAS.map((p) => p.employeeId).join(","), "--adminPrincipalId", adminPrincipal.id,
    "--reason", "Local browser network harness: enrol the four Parts-family synthetic personas for governed sign-in", "--operator", "network-harness",
    "--credentialsOut", cfg.credentialsFile, "--apply",
  ]);
  const out = JSON.parse(r.stdout);
  log(`enrolment: ${out.outcome} ${out.personas.map((p) => `${p.employeeId}=${p.outcome}`).join(" ")}`);
}

writeFileSync(cfg.worldFile, `${JSON.stringify(world, null, 2)}\n`);
await pool.end();
log(`world written: ${cfg.worldFile}`);
