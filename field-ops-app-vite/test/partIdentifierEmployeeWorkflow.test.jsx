// CAT-2 (docs/audits/firebase-retirement-equivalence-2026-10-11): the Parts Manager's identifier (barcode / SKU)
// workflows on Part Detail, against the REAL Catalog API contract -- not a mocked service response.
//
// PartIdentifiersSection runs with its DEFAULT client: the real usePartIdentifiers hook, the real
// services/partAliasCallableClient.js adapter and the real catalogApiClient.callCatalogApi. Only the network is
// replaced, and it answers with the bytes the real server produced for the same request
// (test/fixtures/catalogPartIdentifierContract.json, proven against PostgreSQL by
// functions/test/catalogPartIdentifierEmployeeContractPostgres.test.mjs). Each write also asserts the request the
// screen sent matches the one the server was proven against.
import { afterEach, describe, it, expect, vi } from "vitest";
import { render, screen, cleanup, fireEvent, waitFor, within } from "@testing-library/react";
import CONTRACT from "./fixtures/catalogPartIdentifierContract.json";

const hold = vi.hoisted(() => ({ held: false }));
vi.mock("../src/config/catalogMutationHold.js", async (orig) => ({ ...(await orig()), CATALOG_MUTATION_HOLD: hold }));
// The transport is switched on only in platform-sandbox; this proves the sandbox behaviour.
vi.mock("../src/config/partIdentifierReadiness.js", async (orig) => ({ ...(await orig()), PART_IDENTIFIER_TRANSPORT_READY: true }));

// The network. Each operation answers the next recorded scenario queued for it; everything above it is production code.
const net = vi.hoisted(() => ({ queues: {}, sent: [] }));
vi.mock("../src/services/catalogApiClient.js", async (orig) => {
  const real = await orig();
  const fetchImpl = async (url, init) => {
    const body = JSON.parse(init.body);
    net.sent.push(body);
    const name = (net.queues[body.operation] ?? []).shift();
    if (!name) throw new Error(`no recorded answer queued for ${body.operation}`);
    const scenario = net.CONTRACT.scenarios[name];
    return { ok: scenario.status >= 200 && scenario.status < 300, status: scenario.status, json: async () => scenario.body };
  };
  return { ...real, catalogApiClient: Object.freeze({
    call: (operation, input) => real.callCatalogApi(operation, input, { baseUrl: "https://eos.test", getIdToken: async () => "employee-token", fetchImpl }),
  }) };
});

import PartIdentifiersSection from "../src/shared/partMaster/PartIdentifiersSection.jsx";

net.CONTRACT = CONTRACT;
afterEach(() => { cleanup(); net.queues = {}; net.sent = []; });

function wire(queues) { net.queues = Object.fromEntries(Object.entries(queues).map(([k, v]) => [k, [...v]])); }
const renderSection = () => render(<PartIdentifiersSection partId="PRT-ALIAS-1" partNumber="PRT-ALIAS-1" />);
const sentFor = (operation) => net.sent.filter((b) => b.operation === operation);
const rowOf = async (value) => (await screen.findByText(value)).closest("tr");

function expectSameRequest(operation, scenarioName) {
  const [sent] = sentFor(operation);
  const { idempotencyKey: _sentKey, ...sentInput } = sent.input;
  const { idempotencyKey: _provenKey, ...provenInput } = CONTRACT.scenarios[scenarioName].request.input;
  expect(sentInput).toEqual(provenInput); // the key is per intent, generated by the hook
}

describe("Barcodes & Identifiers -- the Parts Manager sees the Part's identifiers", () => {
  it("the identifiers the server holds are LISTED (they used to render as 'no identifiers')", async () => {
    wire({ listPartAliases: ["listBothActive"] });
    renderSection();
    const table = await screen.findByRole("table", { name: /identifiers for PRT-ALIAS-1/i });
    expect(within(table).getByText("012345678905")).toBeTruthy();
    expect(within(table).getByText("SKU-CONTRACT-1")).toBeTruthy();
    expect(screen.queryByText(/no identifiers/i)).toBeNull();
  });

  it("an INACTIVE identifier is shown, with Reactivate offered", async () => {
    wire({ listPartAliases: ["listAfterDeactivate"] });
    renderSection();
    const row = await rowOf("SKU-CONTRACT-1");
    expect(within(row).getByRole("button", { name: /^reactivate$/i })).toBeTruthy();
    expect(within(await rowOf("012345678905")).getByRole("button", { name: /^deactivate$/i })).toBeTruthy();
  });

  it("an employee without the read+manage pair is told it is a denial, not 'no identifiers'", async () => {
    wire({ listPartAliases: ["listDenied"] });
    renderSection();
    expect(await screen.findByText(/not authorized/i)).toBeTruthy();
    expect(screen.queryByRole("table")).toBeNull();
  });
});

describe("Barcodes & Identifiers -- the Parts Manager maintains identifiers", () => {
  async function addIdentifier(type, value) {
    await screen.findByLabelText(/^type$/i);
    fireEvent.change(screen.getByLabelText(/^type$/i), { target: { value: type } });
    fireEvent.change(screen.getByLabelText(/^value$/i), { target: { value } });
    fireEvent.click(screen.getByRole("button", { name: /add identifier/i }));
  }

// A success shows no banner on this section: the proof is that the list is RE-READ from the server and shows the
// new state, with no error line. (The banner only ever renders non-applied outcomes.)
const noErrorShown = () => {
  expect(screen.queryByText(/could not be completed/i)).toBeNull();
  expect(screen.queryByText(/not authorized/i)).toBeNull();
};

  it("adding a barcode succeeds and the list is re-read from the server, now showing it", async () => {
    wire({ listPartAliases: ["listEmpty", "listBothActive"], createPartAlias: ["createApplied"] });
    renderSection();
    await addIdentifier("UPC", "012345678905");
    await waitFor(() => expect(sentFor("listPartAliases")).toHaveLength(2));
    expectSameRequest("createPartAlias", "createApplied");
    const table = await screen.findByRole("table", { name: /identifiers for PRT-ALIAS-1/i });
    expect(within(table).getByText("012345678905")).toBeTruthy();
    noErrorShown();
  });

  it("an identical resend is reported as already recorded", async () => {
    wire({ listPartAliases: ["listEmpty", "listBothActive"], createPartAlias: ["createReplayed"] });
    renderSection();
    await addIdentifier("UPC", "012345678905");
    await screen.findByText(/already recorded/i);
  });

  it("a barcode owned by another part is reported as already recorded elsewhere, not a generic failure", async () => {
    wire({ listPartAliases: ["listEmpty"], createPartAlias: ["createTaken"] });
    renderSection();
    await addIdentifier("UPC", "012345678905");
    await screen.findByText(/already recorded\. check the list below/i);
    expect(screen.queryByText(/could not be completed/i)).toBeNull();
  });

  it("an employee without inventory.catalog.manage is told so", async () => {
    wire({ listPartAliases: ["listEmpty"], createPartAlias: ["createDenied"] });
    renderSection();
    await addIdentifier("SUPPLIER_SKU", "SKU-DENIED-1");
    await screen.findByText(/not authorized to manage part identifiers/i);
  });

  it("deactivating an identifier succeeds and the row now offers Reactivate (unreachable before)", async () => {
    wire({ listPartAliases: ["listBothActive", "listAfterDeactivate"], deactivatePartAlias: ["deactivateApplied"] });
    renderSection();
    fireEvent.click(within(await rowOf("SKU-CONTRACT-1")).getByRole("button", { name: /^deactivate$/i }));
    await waitFor(() => expect(sentFor("listPartAliases")).toHaveLength(2));
    expectSameRequest("deactivatePartAlias", "deactivateApplied");
    noErrorShown();
    await waitFor(async () => expect(within(await rowOf("SKU-CONTRACT-1")).getByRole("button", { name: /^reactivate$/i })).toBeTruthy());
  });

  it("deactivating an identifier someone else already deactivated says so", async () => {
    wire({ listPartAliases: ["listBothActive"], deactivatePartAlias: ["deactivateAlready"] });
    renderSection();
    fireEvent.click(within(await rowOf("SKU-CONTRACT-1")).getByRole("button", { name: /^deactivate$/i }));
    await screen.findByText(/already in that state/i);
  });

  it("a stale deactivate says someone else changed the identifier", async () => {
    wire({ listPartAliases: ["listBothActive"], deactivatePartAlias: ["deactivateStale"] });
    renderSection();
    fireEvent.click(within(await rowOf("012345678905")).getByRole("button", { name: /^deactivate$/i }));
    await screen.findByText(/someone else changed this identifier/i);
  });

  it("reactivating succeeds and the list is re-read", async () => {
    wire({ listPartAliases: ["listAfterDeactivate", "listAfterReactivate"], reactivatePartAlias: ["reactivateApplied"] });
    renderSection();
    fireEvent.click(within(await rowOf("SKU-CONTRACT-1")).getByRole("button", { name: /^reactivate$/i }));
    await waitFor(() => expect(sentFor("listPartAliases")).toHaveLength(2));
    expectSameRequest("reactivatePartAlias", "reactivateApplied");
    noErrorShown();
    await waitFor(async () => expect(within(await rowOf("SKU-CONTRACT-1")).getByRole("button", { name: /^deactivate$/i })).toBeTruthy());
  });
});
